/* ---------- 字符渲染 ---------- */

/* fb 后端：画一个字符格（8x16）。双宽字符只画左半。
 * 每像素写前验证边界，防 panic 时二次 fault。 */
static void pr_render_char(char c, int x, int y, uint32_t fg, uint32_t bg) {
    int px = x * 8;
    int py = y * 16;
    if (px < 0 || py < 0) return;
    if ((uint32_t)px + 8 > g_pr.fb_w) return;
    if ((uint32_t)py + 16 > g_pr.fb_h) return;

    /* 先填背景 */
    for (int j = 0; j < 16; j++) {
        uint32_t *row = g_pr.fb + (py + j) * g_pr.fb_pitch_px + px;
        for (int i = 0; i < 8; i++) row[i] = bg;
    }

    /* 优先用 font 子系统 */
    int gw = 8;
    const uint8_t *g = font_glyph((uint8_t)c, &gw);
    if (g && gw == 8) {
        for (int j = 0; j < 16; j++) {
            uint8_t bits = g[j];
            uint32_t *row = g_pr.fb + (py + j) * g_pr.fb_pitch_px + px;
            for (int i = 0; i < 8; i++)
                if (bits & (0x80 >> i)) row[i] = fg;
        }
        return;
    }
    if (g && gw == 16) {
        for (int j = 0; j < 16; j++) {
            uint8_t bits = g[j * 2];
            uint32_t *row = g_pr.fb + (py + j) * g_pr.fb_pitch_px + px;
            for (int i = 0; i < 8; i++)
                if (bits & (0x80 >> i)) row[i] = fg;
        }
        return;
    }

    /* font 未加载或非 ASCII：用内置 8x8 兜底，上下各留 4 行黑边 */
    if ((uint8_t)c < 0x20 || (uint8_t)c > 0x7E) return;
    const uint8_t *b = g_builtin_8x8[(uint8_t)c - 0x20];
    for (int j = 0; j < 8; j++) {
        uint8_t bits = b[j];
        uint32_t *row = g_pr.fb + (py + 4 + j) * g_pr.fb_pitch_px + px;
        for (int i = 0; i < 8; i++)
            if (bits & (0x80 >> i)) row[i] = fg;
    }
}

static void pr_render_char_vga(char c, int x, int y, uint8_t attr) {
    if (x < 0 || x >= 80 || y < 0 || y >= 25) return;
    g_pr.vga[y * 80 + x] = ((uint16_t)attr << 8) | (uint8_t)c;
}

/* 按当前 backend 画一个字符格 */
static void pr_render(char c, int x, int y) {
    if (g_pr.backend == 0) {
        pr_render_char(c, x, y, g_pr.cur_fg, g_pr.cur_bg);
    } else if (g_pr.backend == 1) {
        /* VGA：白底黑字 = 0x70，黑底白字 = 0x07 */
        uint8_t attr = (g_pr.cur_bg == 0xFFFFFF) ? 0x70 : 0x07;
        pr_render_char_vga(c, x, y, attr);
    } else {
        (void)x; (void)y;
        serial_write_char(c);
    }
}

/* ---------- 光标与滚动 ---------- */

static void pr_scroll(void) {
    if (g_pr.backend == 0) {
        uint32_t shift = 16 * g_pr.fb_pitch_px * 4;
        uint32_t total = g_pr.fb_h * g_pr.fb_pitch_px * 4;
        if (shift < total) {
            memmove(g_pr.fb, (uint8_t*)g_pr.fb + shift, total - shift);
        }
        /* 最后 16 行填背景 */
        uint32_t start = (g_pr.fb_h - 16) * g_pr.fb_pitch_px;
        for (uint32_t i = start; i < g_pr.fb_h * g_pr.fb_pitch_px; i++)
            g_pr.fb[i] = g_pr.cur_bg;
    } else if (g_pr.backend == 1) {
        for (int i = 0; i < 80 * 24; i++) g_pr.vga[i] = g_pr.vga[i + 80];
        uint8_t attr = (g_pr.cur_bg == 0xFFFFFF) ? 0x70 : 0x07;
        uint16_t blank = ((uint16_t)attr << 8) | ' ';
        for (int i = 0; i < 80; i++) g_pr.vga[80 * 24 + i] = blank;
    }
    g_pr.cur_y = g_pr.rows - 1;
}

static void pr_newline(void) {
    g_pr.cur_x = 0;
    g_pr.cur_y++;
    if (g_pr.cur_y >= g_pr.rows) pr_scroll();
}

static void pr_putc(char c) {
    /* fb / vga 后端也同步串口一份，防 fb 不可见（GRUB 图形模式）时丢失信息 */
    if (g_pr.backend != 2) serial_write_char(c);

    if (g_pr.backend == 2) {
        serial_write_char(c);
        return;
    }

    if (c == '\n') { pr_newline(); return; }
    if (c == '\r') { g_pr.cur_x = 0; return; }
    if (c == '\t') {
        int next = (g_pr.cur_x + 8) & ~7;
        while (g_pr.cur_x < next) {
            if (g_pr.cur_x >= g_pr.cols) { pr_newline(); break; }
            pr_render(' ', g_pr.cur_x, g_pr.cur_y);
            g_pr.cur_x++;
        }
        return;
    }
    if ((unsigned char)c < 0x20) return;
    if (g_pr.cur_x >= g_pr.cols) pr_newline();
    pr_render(c, g_pr.cur_x, g_pr.cur_y);
    g_pr.cur_x++;
}

static void pr_puts(const char *s) {
    while (*s) pr_putc(*s++);
}

static void pr_vprintf(const char *fmt, va_list ap) {
    char buf[512];
    vsnprintf(buf, sizeof(buf), fmt, ap);
    pr_puts(buf);
}

static void pr_printf(const char *fmt, ...) {
    char buf[512];
    va_list ap;
    va_start(ap, fmt);
    vsnprintf(buf, sizeof(buf), fmt, ap);
    va_end(ap);
    pr_puts(buf);
}

/* ---------- 后端选择 ---------- */

static int pr_try_fb(void) {
    struct fb_info *fb = fb_get();
    if (!fb || !fb->valid) return 0;
    if (fb->bpp != 32) return 0;
    if (!fb->virt) return 0;
    if (fb->width == 0 || fb->height == 0) return 0;

    g_pr.backend = 0;
    g_pr.fb = fb->virt;
    g_pr.fb_w = fb->width;
    g_pr.fb_h = fb->height;
    g_pr.fb_pitch_px = fb->pitch / 4;
    g_pr.cols = (int)(fb->width / 8);
    g_pr.rows = (int)(fb->height / 16);
    g_pr.cur_x = 0;
    g_pr.cur_y = 0;
    g_pr.cur_fg = 0xFFFFFF;
    g_pr.cur_bg = 0x000000;

    uint32_t total = g_pr.fb_h * g_pr.fb_pitch_px;
    for (uint32_t i = 0; i < total; i++) g_pr.fb[i] = 0x000000;
    return 1;
}

static int pr_try_vga(void) {
    g_pr.backend = 1;
    g_pr.vga = (volatile uint16_t*)0xB8000;
    g_pr.cols = 80;
    g_pr.rows = 25;
    g_pr.cur_x = 0;
    g_pr.cur_y = 0;
    g_pr.cur_fg = 0xFFFFFF;
    g_pr.cur_bg = 0x000000;
    for (int i = 0; i < 80 * 25; i++)
        g_pr.vga[i] = ((uint16_t)0x07 << 8) | ' ';
    return 1;
}

static void pr_fallback_serial(void) {
    g_pr.backend = 2;
    g_pr.cols = 80;
    g_pr.rows = 25;
    g_pr.cur_x = 0;
    g_pr.cur_y = 0;
    g_pr.cur_fg = 0xFFFFFF;
    g_pr.cur_bg = 0x000000;
}

/* ---------- dump 片段 ---------- */

static void pr_dump_regs(const struct registers *r) {
    if (!r) return;
    pr_puts("\n  --- registers ---\n");
    pr_printf("  eax=%08X ebx=%08X ecx=%08X edx=%08X\n",
              r->eax, r->ebx, r->ecx, r->edx);
    pr_printf("  esi=%08X edi=%08X ebp=%08X esp=%08X\n",
              r->esi, r->edi, r->ebp, r->esp);
    pr_printf("  eip=%08X cs=%04X eflags=%08X\n",
              r->eip, r->cs, r->eflags);
    pr_printf("  int=%u err=%08X\n",
              (unsigned)r->int_no, r->err_code);
    pr_printf("  user_esp=%08X user_ss=%04X\n",
              r->user_esp, r->user_ss);
}

static void pr_dump_task(struct task *t) {
    if (!t) {
        pr_puts("\n  --- current process --- (none)\n");
        return;
    }
    pr_puts("\n  --- current process ---\n");
    pr_printf("  pid=%u state=%u class=%u caps=0x%X\n",
              t->pid, t->state, (unsigned)t->class, t->caps);
    if (t->image[0])
        pr_printf("  image=%s\n", t->image);
    pr_printf("  creator_pid=%u entry=%08X\n",
              t->creator_pid, t->entry_point);
    pr_printf("  cwd=%s:%s\n",
              t->cwd_volume[0] ? t->cwd_volume : "?",
              t->cwd_path[0] ? t->cwd_path : "/");
    pr_printf("  heap=[%08X, %08X) brk=%08X\n",
              t->heap_base, t->heap_limit, t->heap_brk);

    int vma_count = 0;
    for (struct vma *v = t->vma_list; v; v = v->next) vma_count++;
    pr_printf("  vma_count=%d\n", vma_count);
}

static void pr_dump_log(void) {
    int n = log_ring_size();
    if (n <= 0) {
        pr_puts("\n  --- last log --- (empty)\n");
        return;
    }

    pr_puts("\n  --- last log ---\n");

    /* 统计总行数 */
    int lines = 0;
    for (int i = 0; i < n; i++)
        if (log_ring_at(i) == '\n') lines++;

    /* 只保留最后 30 行 */
    int start = 0;
    if (lines > 30) {
        int target = lines - 30;
        int count = 0;
        for (int i = 0; i < n; i++) {
            if (log_ring_at(i) == '\n') {
                count++;
                if (count == target) { start = i + 1; break; }
            }
        }
    }

    for (int i = start; i < n; i++) {
        char c = log_ring_at(i);
        if (c) pr_putc(c);
    }
    if (log_ring_at(n - 1) != '\n') pr_putc('\n');
}

/* ---------- 入口 ---------- */

static void pr_begin(const char *file, uint32_t line) {
    __asm__ volatile("cli");

    if (!pr_try_fb()) {
        if (!pr_try_vga()) pr_fallback_serial();
    }

    if (g_pr.backend != 2) {
        /* 标题行：白底黑字 */
        g_pr.cur_fg = 0x000000;
        g_pr.cur_bg = 0xFFFFFF;
        pr_puts("================ HELIUMOS KERNEL PANIC ================\n");
        g_pr.cur_fg = 0xFFFFFF;
        g_pr.cur_bg = 0x000000;
    } else {
        pr_puts("================ HELIUMOS KERNEL PANIC ================\n");
    }

    pr_printf("\n  Stop code: 0x%04X\n", line);
    pr_printf("  Location:  %s:%u\n\n", file, line);
}

static void pr_end(void) {
    uint32_t cr2, cr3;
    __asm__ volatile("mov %%cr2, %0" : "=r"(cr2));
    __asm__ volatile("mov %%cr3, %0" : "=r"(cr3));
    pr_printf("\n  cr2=%08X  cr3=%08X\n", cr2, cr3);
    pr_puts("\n  System halted. Reboot to continue.\n");
}

void panic_at(const char *file, uint32_t line, const char *fmt, ...) {
    pr_begin(file, line);

    va_list ap;
    va_start(ap, fmt);
    pr_vprintf(fmt, ap);
    va_end(ap);
    pr_puts("\n");

    pr_dump_log();
    pr_dump_task(get_current_task());
    pr_end();

    halt_forever();
}

void panic_regs_at(const struct registers *regs,
                   const char *file, uint32_t line, const char *fmt, ...) {
    pr_begin(file, line);

    va_list ap;
    va_start(ap, fmt);
    pr_vprintf(fmt, ap);
    va_end(ap);
    pr_puts("\n");

    pr_dump_regs(regs);
    pr_dump_log();
    pr_dump_task(get_current_task());
    pr_end();

    halt_forever();
}