#!/bin/bash
# Build TinyCC from source for HeliumOS.
#
# The host tcc/libtcc objects are built with the host gcc.  The final TCC.ELF
# is linked with HeliumOS crt0.o/libc.a; target paths are volume-prefixed
# (SYS:/INCLUDE, SYS:/LIB) because TCC runs inside HeliumOS.
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SRC="$ROOT/third_party/tinycc"
OUT="$ROOT/build/tcc"
LIBC_INC="$ROOT/user/libc/include"
LOG="$ROOT/build/tcc_build.log"
GCC_MAJOR="$(gcc -dumpversion | cut -d. -f1)"
GCC_MINOR="$(gcc -dumpversion | cut -d. -f2)"
LIBGCC="$(gcc -m32 -print-libgcc-file-name)"

mkdir -p "$OUT" "$ROOT/build"
: > "$LOG"

if [ ! -f "$ROOT/build/libc.a" ] || [ ! -f "$ROOT/build/crt0.o" ]; then
    echo "build_tcc: build/libc.a and build/crt0.o are required" >&2
    echo "           run: make libc.a build/crt0.o" >&2
    exit 1
fi

# TinyCC's configure-generated files are intentionally local to the source
# tree (upstream .gitignore ignores them).
cat > "$SRC/config.h" <<EOF
/* Generated by HeliumOS tools/build_tcc.sh - do not modify */
#define TCC_VERSION "0.9.28rc"
#define CC_NAME CC_gcc
#define GCC_MAJOR $GCC_MAJOR
#define GCC_MINOR $GCC_MINOR

#if !(TCC_TARGET_I386 || TCC_TARGET_X86_64 || TCC_TARGET_ARM || TCC_TARGET_ARM64 || TCC_TARGET_RISCV64 || TCC_TARGET_C67)
#define TCC_TARGET_I386 1
#define CONFIG_TCC_SYSINCLUDEPATHS "SYS:/INCLUDE"
#define CONFIG_TCC_LIBPATHS "SYS:/LIB"
#define CONFIG_TCC_CRTPREFIX "SYS:/LIB"
#define CONFIG_TCCDIR "SYS:/LIB"
#define CONFIG_TRIPLET "i386-linux-gnu"
#define CONFIG_OS_RELEASE "helium"
#endif

#define CONFIG_TCC_PREDEFS 1
#define CONFIG_TCC_STATIC 1
#define CONFIG_TCC_BACKTRACE 0
EOF

cat > "$SRC/config.mak" <<EOF
# Generated by HeliumOS tools/build_tcc.sh - do not modify
prefix=/usr/local
bindir=\$(DESTDIR)/usr/local/bin
tccdir=\$(DESTDIR)/usr/local/lib/tcc
libdir=\$(DESTDIR)/usr/local/lib
includedir=\$(DESTDIR)/usr/local/include
mandir=\$(DESTDIR)/usr/local/share/man
infodir=\$(DESTDIR)/usr/local/share/info
docdir=\$(DESTDIR)/usr/local/share/doc
CC=gcc
CC_NAME=gcc
GCC_MAJOR=$GCC_MAJOR
GCC_MINOR=$GCC_MINOR
AR=ar
LIBSUF=.a
EXESUF=
DLLSUF=.so
CFLAGS=-m32 -std=gnu99 -fno-stack-protector -U_FORTIFY_SOURCE -D_GNU_SOURCE -DCONFIG_TCC_SEM=0 -Wdeclaration-after-statement -Wno-unused-result
LDFLAGS=-m32
ARCH=i386
TARGETOS=Linux
BUILDOS=Linux
VERSION=0.9.28rc
TOPSRC=\$(TOP)
CONFIG_i386=yes
EOF

cd "$SRC" || exit 1
make clean >>"$LOG" 2>&1 || true

echo "=== build host tcc/libtcc ===" | tee -a "$LOG"
make -j"$(nproc)" tcc libtcc.a >>"$LOG" 2>&1
if [ $? -ne 0 ]; then
    echo "build_tcc: host tcc/libtcc build failed" >&2
    tail -40 "$LOG" >&2
    exit 1
fi

echo "=== host tcc smoke test ===" | tee -a "$LOG"
printf 'int main(void) { return 0; }\n' > "$OUT/smoke.c"
if ! "$SRC/tcc" -c "$OUT/smoke.c" -o "$OUT/smoke.o" >>"$LOG" 2>&1; then
    echo "build_tcc: host tcc smoke test failed" >&2
    tail -40 "$LOG" >&2
    exit 1
fi

echo "=== build libtcc1.a ===" | tee -a "$LOG"
# HeliumOS does not need tcov/backtrace/bounds-check runtime.  Build the
# minimal runtime object that the original HeliumOS port used.
(cd "$SRC/lib" && ../tcc -c libtcc1.c -o libtcc1.o \
    -B.. -I.. -I"$LIBC_INC" >>"$LOG" 2>&1 && \
    ar rcs libtcc1.a libtcc1.o >>"$LOG" 2>&1)
if [ $? -ne 0 ] || [ ! -f "$SRC/lib/libtcc1.a" ]; then
    echo "build_tcc: libtcc1.a build failed" >&2
    tail -40 "$LOG" >&2
    exit 1
fi
cp "$SRC/lib/libtcc1.a" "$OUT/libtcc1.a"

# The host tcc is built against host fcntl.h, but the same objects are
# linked into TCC.ELF and therefore must pass HeliumOS FS_O_* values to
# open().  Rebuild tcc.o/libtcc.a for the target with the flag compatibility
# layer in tcc.h.  libtcc1.a was already built by the host tcc above.
TCC_BASE_CFLAGS="$(sed -n 's/^CFLAGS=//p' "$SRC/config.mak")"
echo "=== rebuild tcc/libtcc for HeliumOS ===" | tee -a "$LOG"
make clean >>"$LOG" 2>&1 || true
make -j"$(nproc)" tcc libtcc.a \
    CFLAGS="$TCC_BASE_CFLAGS -DCONFIG_TCC_HELIUMOS" >>"$LOG" 2>&1
if [ $? -ne 0 ]; then
    echo "build_tcc: target tcc/libtcc build failed" >&2
    tail -40 "$LOG" >&2
    exit 1
fi

cp "$SRC/tcc.o" "$OUT/tcc.o"
cp "$SRC/libtcc.a" "$OUT/libtcc.a"

echo "=== link HeliumOS TCC.ELF ===" | tee -a "$LOG"
gcc -m32 -static -nostdlib \
    -Wl,-T,"$ROOT/user/linker.ld" \
    -Wl,--start-group \
        "$OUT/tcc.o" "$OUT/libtcc.a" \
        "$ROOT/build/crt0.o" "$ROOT/build/libc.a" \
    -Wl,--end-group \
    "$LIBGCC" \
    -o "$ROOT/build/TCC.ELF" >>"$LOG" 2>&1
if [ $? -ne 0 ]; then
    echo "build_tcc: TCC.ELF link failed" >&2
    tail -40 "$LOG" >&2
    exit 1
fi

echo "=== TCC.ELF generated ===" | tee -a "$LOG"
file "$ROOT/build/TCC.ELF" | tee -a "$LOG"
ls -l "$ROOT/build/TCC.ELF" | tee -a "$LOG"
echo "log: $LOG"
